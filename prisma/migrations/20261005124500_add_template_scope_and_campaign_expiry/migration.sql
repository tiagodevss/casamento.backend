-- Add explicit privacy scope for templates and temporal validity for campaigns.
ALTER TYPE "CommunicationCampaignStatus" ADD VALUE IF NOT EXISTS 'EXPIRED';

DO $$ BEGIN
  CREATE TYPE "CommunicationTemplateScope" AS ENUM ('GENERAL', 'PARTY');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

ALTER TABLE "CommunicationTemplate"
ADD COLUMN IF NOT EXISTS "scope" "CommunicationTemplateScope" NOT NULL DEFAULT 'GENERAL';

UPDATE "CommunicationTemplate"
SET "scope" = 'PARTY'
WHERE "key" IN ('INFO_PARTY', 'WEEK_PARTY', 'TOMORROW_PARTY', 'TODAY_PARTY');

ALTER TABLE "CommunicationCampaign"
ADD COLUMN IF NOT EXISTS "expiresAt" TIMESTAMP(3);

UPDATE "CommunicationCampaign" c
SET "expiresAt" = CASE t."key"
  WHEN 'CERIMONIALISTA_INTRO' THEN TIMESTAMP WITH TIME ZONE '2026-09-09 00:00:00-03'
  WHEN 'RSVP_REMINDER_1' THEN TIMESTAMP WITH TIME ZONE '2026-09-23 00:00:00-03'
  WHEN 'RSVP_REMINDER_2' THEN TIMESTAMP WITH TIME ZONE '2026-09-30 00:00:00-03'
  WHEN 'RSVP_FINAL' THEN TIMESTAMP WITH TIME ZONE '2026-10-02 00:00:00-03'
  WHEN 'SITE_GIFTS' THEN TIMESTAMP WITH TIME ZONE '2026-10-31 00:00:00-03'
  WHEN 'INFO_CEREMONY' THEN TIMESTAMP WITH TIME ZONE '2026-11-07 00:00:00-03'
  WHEN 'INFO_PARTY' THEN TIMESTAMP WITH TIME ZONE '2026-11-07 00:00:00-03'
  WHEN 'WEEK_CEREMONY' THEN TIMESTAMP WITH TIME ZONE '2026-11-13 00:00:00-03'
  WHEN 'WEEK_PARTY' THEN TIMESTAMP WITH TIME ZONE '2026-11-13 00:00:00-03'
  WHEN 'TOMORROW_CEREMONY' THEN TIMESTAMP WITH TIME ZONE '2026-11-14 00:00:00-03'
  WHEN 'TOMORROW_PARTY' THEN TIMESTAMP WITH TIME ZONE '2026-11-14 00:00:00-03'
  WHEN 'TODAY_CEREMONY' THEN TIMESTAMP WITH TIME ZONE '2026-11-14 16:00:00-03'
  WHEN 'TODAY_PARTY' THEN TIMESTAMP WITH TIME ZONE '2026-11-14 16:00:00-03'
  WHEN 'THANK_YOU' THEN TIMESTAMP WITH TIME ZONE '2026-11-30 23:59:00-03'
  ELSE c."expiresAt"
END
FROM "CommunicationTemplate" t
WHERE c."templateId" = t."id"
  AND c."expiresAt" IS NULL;

CREATE INDEX IF NOT EXISTS "CommunicationCampaign_status_expiresAt_idx"
ON "CommunicationCampaign"("status", "expiresAt");
